import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(__dirname, '..');
const repoRoot = resolve(pkgRoot, '../..');
const outDir = resolve(pkgRoot, 'pkg');

function findBinary(name, cacheSubdirPrefix, relativeBinPath) {
  try {
    const found = execFileSync('which', [name], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    if (found) return found;
  } catch {
    // Fall back to wasm-pack cache directory.
  }
  const cacheDir = join(homedir(), '.cache', '.wasm-pack');
  if (existsSync(cacheDir)) {
    for (const entry of readdirSync(cacheDir)) {
      if (entry.startsWith(cacheSubdirPrefix)) {
        const candidate = join(cacheDir, entry, ...relativeBinPath);
        if (existsSync(candidate)) return candidate;
      }
    }
  }
  return null;
}

const rustflags = [process.env.RUSTFLAGS, '--cfg getrandom_backend="wasm_js"']
  .filter(Boolean)
  .join(' ');

const env = {
  ...process.env,
  RUSTFLAGS: rustflags,
};

// 1. Build the cdylib for wasm32-unknown-unknown in release mode.
execFileSync(
  'cargo',
  [
    'build',
    '--manifest-path',
    resolve(repoRoot, 'Cargo.toml'),
    '-p',
    'lexel-wasm',
    '--target',
    'wasm32-unknown-unknown',
    '--release',
    '--offline',
  ],
  { stdio: 'inherit', env, cwd: repoRoot },
);

const wasmInput = resolve(repoRoot, 'target/wasm32-unknown-unknown/release/lexel_wasm.wasm');
if (!existsSync(wasmInput)) {
  throw new Error(`Expected compiled WASM artifact at ${wasmInput}`);
}

mkdirSync(outDir, { recursive: true });

// 2. Generate web-target JS + TypeScript bindings via wasm-bindgen.
const wasmBindgen = findBinary('wasm-bindgen', 'wasm-bindgen-', ['wasm-bindgen']);
if (!wasmBindgen) {
  throw new Error(
    'wasm-bindgen CLI not found on PATH or in ~/.cache/.wasm-pack. Install with `cargo install wasm-bindgen-cli --version 0.2.129`.',
  );
}

execFileSync(
  wasmBindgen,
  ['--target', 'web', '--out-dir', outDir, '--out-name', 'lexel_wasm', wasmInput],
  { stdio: 'inherit', env },
);

// 3. Optimize the .wasm binary size with wasm-opt when available.
const wasmOutput = resolve(outDir, 'lexel_wasm_bg.wasm');
const rawBytes = statSync(wasmOutput).size;
const wasmOpt = findBinary('wasm-opt', 'wasm-opt-', ['bin', 'wasm-opt']);
if (wasmOpt) {
  try {
    execFileSync(
      wasmOpt,
      [
        '-Oz',
        '--enable-bulk-memory',
        '--enable-sign-ext',
        '--enable-mutable-globals',
        '--enable-nontrapping-float-to-int',
        '-o',
        wasmOutput,
        wasmOutput,
      ],
      { stdio: 'inherit', env },
    );
  } catch (err) {
    console.warn(
      `wasm-opt skipped due to error: ${err instanceof Error ? err.message : String(err)}`,
    );
  }
}

for (const filename of ['.gitignore', 'package.json', 'README.md']) {
  const target = resolve(outDir, filename);
  if (existsSync(target)) {
    rmSync(target, { force: true });
  }
}

// Mark generated wasm-bindgen glue so workspace Biome lint/assist checks stay clean.
const generatedHeader =
  '/* biome-ignore-all lint: generated by wasm-bindgen */\n/* biome-ignore-all assist: generated by wasm-bindgen */\n';
for (const filename of ['lexel_wasm.js', 'lexel_wasm.d.ts', 'lexel_wasm_bg.wasm.d.ts']) {
  const target = resolve(outDir, filename);
  if (existsSync(target)) {
    const content = readFileSync(target, 'utf8');
    if (!content.startsWith('/* biome-ignore-all lint:')) {
      writeFileSync(target, `${generatedHeader}${content}`, 'utf8');
    }
  }
}
try {
  execFileSync('pnpm', ['exec', 'biome', 'format', '--write', outDir], {
    stdio: 'ignore',
    cwd: repoRoot,
  });
} catch {
  // Ignore if biome is unavailable during standalone WASM builds.
}

const finalBytes = statSync(wasmOutput).size;
const rawMb = (rawBytes / (1024 * 1024)).toFixed(2);
const finalMb = (finalBytes / (1024 * 1024)).toFixed(2);
console.log(
  `Built lexel_wasm_bg.wasm: raw=${rawBytes} bytes (${rawMb} MiB), optimized=${finalBytes} bytes (${finalMb} MiB)`,
);
